"""Serve the pre-built app-design preview pages.

These are **static design mocks**, not the live student app. They render
hardcoded sample data and read nothing from the database, so they are safe to
serve without auth and must never be mistaken for ``/student/*``.

Source lives in ``static/machreach_app`` (``app/*.jsx`` components +
``pages/<id>.jsx`` bootstraps). The committed artifacts ``<id>.prod.html`` and
``<id>.bundle.min.js`` are generated by::

    cd landing_build && node build-app.mjs

Regenerate after editing any source file.
"""
