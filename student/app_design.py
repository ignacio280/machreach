def available_pages() -> dict[str, str]:
    """Slug -> human label, for the index listing."""
    return dict(_PAGES)


def page_exists(slug: str) -> bool:
    return slug in _PAGES


def render_design_page(slug: str) -> str | None:
    """Return the built HTML for a preview page, or None if it isn't built."""
    if slug not in _PAGES:
        return None
    artifact = _APP_DIR / f"{slug}.prod.html"
    if not artifact.is_file():
        return None
    return artifact.read_text(encoding="utf-8")


def render_live_page(slug: str, data: dict, version: str | None = None) -> str | None:
    """Return the exact Claude app shell wired to server-provided live data.

    The version keys the browser cache. It was a hardcoded string, which meant
    the URL of every bundle stayed identical across deploys — and the service
    worker serves /static cache-first, so a returning student kept running the
    JavaScript from their first ever visit. It tracks the deploy now, so a new
    deploy is a new URL and the cache cannot answer with yesterday's code.
    """
    from machreach_core.config import DEPLOY_VERSION

    version = version or DEPLOY_VERSION
    if slug not in _PAGE_CSS:
        return None
    payload = dict(data or {})
    payload["live"] = True
    encoded = base64.b64encode(
        json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    ).decode("ascii")
    styles = "".join(
        f'<link rel="stylesheet" href="/static/machreach_app/app/{name}?v={version}">'
        for name in _PAGE_CSS[slug]
    )
    animation_styles = ""
    if slug == "perfil":
        from student.db import BANNER_ANIM_CSS
        animation_styles = f"<style>{BANNER_ANIM_CSS}</style>"
    elif slug in ("perfil-editar", "tienda"):
        # These two preview many cosmetics at once, so they need the full
        # animation catalog, not just the equipped banner's keyframes.
        from student.db import BANNER_ANIM_CSS, FLAG_ANIM_CSS
        animation_styles = f"<style>{BANNER_ANIM_CSS}{FLAG_ANIM_CSS}</style>"
    return (
        f'<link rel="stylesheet" href="/static/machreach_landing/v6/theme.css?v={version}">'
        + animation_styles
        + styles
        + '<div id="root"></div>'
        + '<script>window.__MACHREACH_APP__=JSON.parse(new TextDecoder().decode('
        + f'Uint8Array.from(atob("{encoded}"),function(c){{return c.charCodeAt(0)}})));</script>'
        + '<script src="/static/machreach_landing/vendor/react.production.min.js"></script>'
        + '<script src="/static/machreach_landing/vendor/react-dom.production.min.js"></script>'
        + f'<script src="/static/machreach_app/{slug}.bundle.min.js?v={version}" defer></script>'
    )
